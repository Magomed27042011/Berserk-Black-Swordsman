#⁡⁢⁣⁢Cверху цикла (Выполняется один раз при старте):⁡
#⁡⁢⁢⁢pygame.init() — запускает все внутренние модули Pygame. Вызывается всегда в самом начале кода⁡
#⁡⁢⁢⁢pygame.display.set_mode((ширина, высота)) — создает окно игры заданного размера.⁡
#⁡⁢⁢⁢pygame.display.set_caption("Название") — меняет текст в заголовке окна.⁡
#⁡⁢⁢⁢clock = pygame.time.Clock() — создает игровой таймер.⁡
#⁡⁢⁢⁢pygame.image.load("путь_к_файлу.png") — загружает картинку в игру.⁡

#⁡⁢⁣⁢Внутри цикла (Выполняется по кругу на каждом кадре)⁡:
#⁡⁢⁢⁢pygame.event.get() — собирает все действия пользователя (нажатия клавиш, движения мыши).⁡
#⁡⁢⁢⁢event.type == pygame.QUIT — проверяет, нажал ли игрок на «крестик», чтобы закрыть окно.⁡
#⁡⁢⁢⁢pygame.key.get_pressed() — возвращает состояние всех клавиш клавиатуры (зажата кнопка или нет).⁡
#⁡⁢⁢⁢screen.fill((R, G, B)) — заливает весь экран одним цветом (очищает прошлый кадр).⁡
#⁡⁢⁢⁢pygame.draw.rect(экран, цвет, (x, y, ширина, высота)) — рисует прямоугольник⁡
#⁡⁢⁢⁢pygame.draw.circle(экран, цвет, (x, y), радиус) — рисует круг.⁡
#⁡⁢⁢⁢screen.blit(картинка, (x, y)) — копирует и отображает картинку на экране в указанных координатах.⁡
#⁡⁢⁢⁢pygame.display.flip() — обновляет всё содержимое экрана. Вызывается в конце каждого кадра.⁡

